#include <common.h>
#include <delay.h>
#include <gpio.h>
#include <soft_spi.h>  // 引入legacy软SPI头文件
#include <configs/rtd1295_common.h>

/* NT7534硬件参数 */
#define NT7534_WIDTH    128
#define NT7534_HEIGHT   64
#define NT7534_PAGE_CNT 8

/* NT7534指令集 */
#define NT7534_CMD_DISPLAY_OFF    0xAE
#define NT7534_CMD_DISPLAY_ON     0xAF
#define NT7534_CMD_SET_PAGE       0xB0
#define NT7534_CMD_SET_COL_HIGH   0x10
#define NT7534_CMD_SET_COL_LOW    0x00
#define NT7534_CMD_SET_ADC_NORMAL 0xA0
#define NT7534_CMD_SET_COM_NORMAL 0xC0
#define NT7534_CMD_SET_POWER      0x2F
#define NT7534_CMD_SET_VOLUME     0x81
#define NT7534_CMD_SET_VOLUME_VAL 0x10

/* 帧缓冲区 */
static u8 nt7534_fb[NT7534_PAGE_CNT][NT7534_WIDTH] = {0};

/* 软SPI片选控制（对接soft_spi_legacy） */
static void nt7534_cs_ctrl(int en)
{
    soft_spi_set_cs(0, en ? 0 : 1);  // 0=使能（低电平），1=禁用（高电平）
    udelay(1);
}

/* 向NT7534发送命令 */
static void nt7534_send_cmd(u8 cmd)
{
    u8 tx_buf[2] = {0x00, cmd};  // 0x00=命令模式(D/C=0)，cmd=指令
    nt7534_cs_ctrl(1);
    soft_spi_xfer(16, tx_buf, NULL, 0);  // 发送16bit（2字节）
    nt7534_cs_ctrl(0);
    udelay(10);
}

/* 向NT7534发送数据 */
static void nt7534_send_data(u8 data)
{
    u8 tx_buf[2] = {0x40, data};  // 0x40=数据模式(D/C=1)，data=像素数据
    nt7534_cs_ctrl(1);
    soft_spi_xfer(16, tx_buf, NULL, 0);
    nt7534_cs_ctrl(0);
    udelay(1);
}

/* NT7534硬件复位 */
static void nt7534_hw_reset(void)
{
    gpio_set_value(SPI_RST_GPIO, 0);
    mdelay(10);
    gpio_set_value(SPI_RST_GPIO, 1);
    mdelay(50);
}

/* 初始化NT7534 */
int nt7534_init(void)
{
    // 硬件复位
    nt7534_hw_reset();

    // 发送初始化指令
    nt7534_send_cmd(NT7534_CMD_DISPLAY_OFF);
    nt7534_send_cmd(NT7534_CMD_SET_ADC_NORMAL);
    nt7534_send_cmd(NT7534_CMD_SET_COM_NORMAL);
    nt7534_send_cmd(NT7534_CMD_SET_POWER);
    nt7534_send_cmd(NT7534_CMD_SET_VOLUME);
    nt7534_send_cmd(NT7534_CMD_SET_VOLUME_VAL);
    nt7534_send_cmd(NT7534_CMD_DISPLAY_ON);

    // 清屏
    nt7534_clear();

    printf("NT7534: Init success!\n");
    return 0;
}

/* 清屏 */
void nt7534_clear(void)
{
    int page, col;
    memset(nt7534_fb, 0, sizeof(nt7534_fb));

    for (page = 0; page < NT7534_PAGE_CNT; page++) {
        nt7534_send_cmd(NT7534_CMD_SET_PAGE | page);
        nt7534_send_cmd(NT7534_CMD_SET_COL_HIGH | 0x00);
        nt7534_send_cmd(NT7534_CMD_SET_COL_LOW | 0x00);

        nt7534_cs_ctrl(1);
        u8 tx_hdr = 0x40;
        soft_spi_xfer(8, &tx_hdr, NULL, 0);  // 先发数据模式标识
        for (col = 0; col < NT7534_WIDTH; col++) {
            soft_spi_xfer(8, &(u8){0x00}, NULL, 0);  // 批量发送0（清屏）
        }
        nt7534_cs_ctrl(0);
    }
}

/* 设置单个像素 */
void nt7534_set_pixel(int x, int y, u8 val)
{
    if (x < 0 || x >= NT7534_WIDTH || y < 0 || y >= NT7534_HEIGHT)
        return;

    int page = y / 8;
    int bit = y % 8;
    if (val)
        nt7534_fb[page][x] |= (1 << bit);
    else
        nt7534_fb[page][x] &= ~(1 << bit);
}

/* 刷新屏幕（帧缓冲区同步到硬件） */
void nt7534_refresh(void)
{
    int page, col;
    for (page = 0; page < NT7534_PAGE_CNT; page++) {
        nt7534_send_cmd(NT7534_CMD_SET_PAGE | page);
        nt7534_send_cmd(NT7534_CMD_SET_COL_HIGH | 0x00);
        nt7534_send_cmd(NT7534_CMD_SET_COL_LOW | 0x00);

        nt7534_cs_ctrl(1);
        u8 tx_hdr = 0x40;
        soft_spi_xfer(8, &tx_hdr, NULL, 0);  // 数据模式标识
        for (col = 0; col < NT7534_WIDTH; col++) {
            soft_spi_xfer(8, &nt7534_fb[page][col], NULL, 0);
        }
        nt7534_cs_ctrl(0);
    }
}

